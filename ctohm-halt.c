void draw_string(unsigned char *buf, int page, int col, const char *str, int invert) {
    while (*str) {
        unsigned char c = (unsigned char)*str;
        if (c < 128 && col + 8 <= 128) {
            for (int i = 0; i < 8; i++) {
                unsigned char b = font8x8[c][i];
                buf[1 + page * 128 + col + i] = invert ? ~b : b;
            }
        }
        col += 7; // Character spacing
        str++;
    }
}

void draw_string_effect(unsigned char *buf, int page, int col, const char *str, int invert, int file) {
    while (*str) {
        unsigned char c = (unsigned char)*str;
        if (c < 128 && col + 8 <= 128) {
            //draw underscore, write the buffer
            for (int i = 0; i < 8; i++) {
                unsigned char b = font8x8['_'][i];
                buf[1 + page * 128 + col + i] = invert ? ~b : b;
            }
            write(file, buf, 1025);
            //there's a delay while the buffer is written, which is perfect for effect

            //clear underscore, draw char
            for (int i = 0; i < 8; i++) {
                unsigned char b = font8x8['_'][i];
                buf[1 + page * 128 + col + i] = invert ? b : ~b;
            }
            for (int i = 0; i < 8; i++) {
                unsigned char b = font8x8[c][i];
                buf[1 + page * 128 + col + i] = invert ? ~b : b;
            }
		    write(file, buf, 1025);
        }
        col += 7; // Character spacing
        str++;
    }
}

int main(int argc, char *argv[]) {
    //if we're rebooting, exit
    if (argc > 1 && strcmp(argv[1], "reboot") == 0) {
        return(0);
    }

    int file = open(I2C_BUS, O_RDWR);
    if (file < 0) return 1;

    if (ioctl(file, I2C_SLAVE, OLED_ADDR) < 0) {
        close(file);
        return 1;
    }

    write(file, init_cmds, sizeof(init_cmds));

    // Reset column/page address bounds
    unsigned char reset_addr[] = {0x00, 0x21, 0x00, 0x7F, 0x22, 0x00, 0x07};
    write(file, reset_addr, sizeof(reset_addr));

    unsigned char buffer[1025];
    buffer[0] = 0x40; // Data stream marker
    memset(buffer + 1, 0x00, 1024); // Clear frame buffer

    // Draw Header Bar (Page 0, Yellow section)
    for (int i = 1; i <= 128; i++) buffer[i] = 0xFF; // Solid white background for header
    draw_string_effect(buffer, 0, 1, ">END OF LINE.", 1, file); // Inverted black text on yellow

    // Draw Main Messages (Pages 3 & 5, Blue section)
    draw_string(buffer, 3, 0, "It is now safe to", 0);
    draw_string(buffer, 4, 0, "  turn off your", 0);
    draw_string(buffer, 5, 0, "   ConnectOhm.", 0);

    write(file, buffer, 1025);
    close(file);
    return 0;
}
